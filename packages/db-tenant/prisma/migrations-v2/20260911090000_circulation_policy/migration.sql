-- ---------------------------------------------------------------------------
-- The version bump
-- ---------------------------------------------------------------------------
--
-- §4.1: the snapshot is "versioned by the trigger-maintained
-- `circulation_policy_version` counter", and trigger-maintained is the whole
-- design. §4.2 makes the argument for the changelog — "a forgotten `emit()`
-- silently breaks replicas and the index forever; a trigger is unforgettable" —
-- and here it is sharper. A forgotten bump does not break a replica: every pod
-- keeps its cached snapshot, the 30-second backstop re-reads the counter, sees
-- no change, and keeps the stale cache. Not for thirty seconds. FOREVER. The
-- librarian edits the loan period, the screen says saved, and every checkout
-- that week is priced by the old one.
--
-- The surface is also larger than the changelog's, not smaller: this phase's
-- service, the simple-mode façade, a phase-30 copy-cataloguing importer, phase
-- 19's copy-forward (PL/pgSQL, which never touches the application at all), a
-- seed script, and a support engineer in `psql`. Seventeen triggers cover all
-- six.
--
-- FOR EACH STATEMENT, NOT FOR EACH ROW. Measured on PG 16.15: a 40-row UPDATE
-- fires a row trigger 40 times and a statement trigger once. Forty `UPDATE`s of
-- the same counter row inside one transaction is 40 dead tuples and 40× the WAL
-- for one librarian's edit, and it would count ROWS TOUCHED rather than POLICY
-- STATES.
--
-- A STATEMENT TRIGGER FIRES ON ZERO AFFECTED ROWS — measured — so
-- `UPDATE circulation_rules SET enabled = true WHERE id = 'typo'` bumps the
-- version. That is over-invalidation, and it is free to accept because the
-- correctness requirement is one-directional: a different policy state MUST get
-- a different version (or a receipt cannot be reproduced and a pod's
-- revalidation misses a change), while a different version need NOT mean a
-- different state (a spurious bump costs one snapshot rebuild). The alternative
-- — a transition table with `IF EXISTS (SELECT 1 FROM new_rows)` — cannot be
-- combined with multiple events, so seventeen triggers would become fifty-one.
--
-- `OR TRUNCATE` IS IN EVERY ONE, and it matters more here than for the
-- changelog. Measured: `TRUNCATE circulation_rules` on 40 rows emits ZERO change
-- events, because the changelog is row-level and cannot see a truncate. Without
-- `OR TRUNCATE` here the version would not move either, and every pod would
-- serve the deleted matrix for ever — fully populated and completely wrong. With
-- it, every pod rebuilds, the resolver raises `NO_MATCHING_RULE`, and the desk
-- refuses to lend. Refusing is correct.
--
-- `version = version + 1` NEEDS NO LOCK OF OURS. Measured: two concurrent bumps
-- from 1 give 3, not 2 — Postgres's ReadCommitted UPDATE re-check re-fetches the
-- newly committed row and re-evaluates the expression against it, the same
-- mechanism that makes `SET balance = balance + 100` safe. A read-then-write in
-- application code, which is what bumping in a service would be, is what loses
-- the update.

CREATE OR REPLACE FUNCTION lbr2_bump_policy_version() RETURNS trigger
LANGUAGE plpgsql AS $lbr2_bump_policy_version$
BEGIN
  -- Unqualified on purpose, resolved through the search_path the caller is
  -- already in — the same reason `lbr2_write_change_event` refuses to pin its
  -- own path: `ALTER FUNCTION … SET search_path = lbr2` stores the schema name
  -- as TEXT, and after phase 20's rename that name does not exist.
  EXECUTE pg_catalog.format(
    'UPDATE %I.circulation_policy_version SET version = version + 1, updated_at = pg_catalog.now() WHERE id = 1',
    TG_TABLE_SCHEMA);
  RETURN NULL;
END;
$lbr2_bump_policy_version$;

