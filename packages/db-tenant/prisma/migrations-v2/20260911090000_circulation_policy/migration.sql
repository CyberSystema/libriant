ALTER TABLE circulation_rules
  ADD COLUMN specificity smallint GENERATED ALWAYS AS (
      (CASE WHEN patron_category_id   IS NOT NULL THEN 32 ELSE 0 END)
    + (CASE WHEN item_type_id         IS NOT NULL THEN 16 ELSE 0 END)
    + (CASE WHEN owning_branch_id     IS NOT NULL THEN  8 ELSE 0 END)
    + (CASE WHEN shelving_location_id IS NOT NULL THEN  4 ELSE 0 END)
    + (CASE WHEN checkout_branch_id   IS NOT NULL THEN  2 ELSE 0 END)
    + (CASE WHEN pickup_branch_id     IS NOT NULL THEN  1 ELSE 0 END)) STORED;

-- Two rules with the same six selectors are not a tie the resolver can break —
-- `compareRank` would fall through to the id, and which of two identical scopes
-- wins would depend on a cuid. COALESCE to '' because NULL never equals NULL in
-- a unique index, so without it the wildcard row is unconstrained and so is
-- every rule with any selector blank.
CREATE UNIQUE INDEX circulation_rules_scope_unique ON circulation_rules (
  COALESCE(patron_category_id, ''), COALESCE(item_type_id, ''),
  COALESCE(owning_branch_id, ''), COALESCE(shelving_location_id, ''),
  COALESCE(checkout_branch_id, ''), COALESCE(pickup_branch_id, ''))
  WHERE enabled AND effective_to IS NULL;

-- AT MOST ONE ENABLED WILDCARD, EVER. §3's predicate exactly — `specificity = 0
-- AND enabled` — and deliberately NOT widened with `effective_to IS NULL`.
-- Widening it would admit two enabled wildcards at once (one expiring, one not),
-- both in force today, both at priority 0 and specificity 0, and `compareRank`
-- would then decide the DEFAULT RULE of the library by comparing two cuids. The
-- narrow predicate makes that state unreachable; scheduling a new default is
-- done by editing the one row, which is also the only way it stays explicable.
CREATE UNIQUE INDEX circulation_rules_default_singleton
  ON circulation_rules ((true))
  WHERE specificity = 0 AND enabled;

-- The matrix editor lists rules to a human, and `/circulation/explain` renders
-- the neighbours a rule beat. Those orderings must agree with `compareRank`,
-- whose id tiebreak is UTF-16 code units, and the tenant collation is ICU el-GR
-- — measured to differ: `r_default < r-default` under ICU and the reverse under
-- C, and `CKV1A2B3C` sorts first under C and mid-list under ICU. Generated cuids
-- provably cannot diverge (the whole `[0-9a-z]` alphabet orders identically
-- under both), but a seeded, imported or human-chosen id can, and a UI that
-- lists rules in a different order than the engine ranks them is the same bug
-- wearing a different hat. This index is what makes `ORDER BY … id COLLATE "C"`
-- cheap for those listings.
CREATE INDEX circulation_rules_listing_idx
  ON circulation_rules (priority DESC, specificity DESC, id COLLATE "C");

