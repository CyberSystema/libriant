-- Generated by `node scripts/gen-changelog-triggers.mjs`. ONLY THE NEW TRIGGERS
-- are here; the function and the nine existing triggers are untouched.
--
-- ALL SIXTEEN NEW TABLES ARE `@replicated`, and the decisive argument is phase
-- 77 rather than a preference. `PolicySnapshot` is a CLOSED value — version,
-- rules, five policy tables, fixed due dates, category limits, calendars — and
-- every one of its fields maps onto a table here with nothing left over. A
-- device missing any one of them does not lend with a slightly wrong due date:
-- §4.1 forbids failing open, so it raises `POLICY_NOT_IN_SNAPSHOT` or
-- `CALENDAR_NOT_DEFINED_FOR` and refuses to lend. Replication here is not an
-- optimisation, it is whether the offline client functions at all.
--
