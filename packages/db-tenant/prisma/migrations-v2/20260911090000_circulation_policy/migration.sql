-- overdue-fine sweep touches every accruing fee every night, so a trigger here
-- would be the single largest producer in the feed — and no consumer reads it
-- yet". These tables are written by a librarian in an admin screen; the whole
-- set changes less in a year than `fees` changes in a minute. Consumers exist
