-- Holds: the queue, and the constraint that makes the acceptance criterion
-- enforceable rather than merely tested.
--
-- §6 phase 17. Two new tables, one enum, four CHECKs, two partial uniques, and
-- the foreign key phase 15 promised `item_transfers.hold_id` when it wrote "no
-- FK: holds is phase 17".
--
-- ============================================================================
-- THE THREE DECISIONS THIS FILE ENCODES
-- ============================================================================
--
-- 1. THE 1.0 BUG IS TURNED INTO A CONSTRAINT VIOLATION, NOT LEFT AS A WRONG
--    NUMBER.
--
--    §3: "The 1.0 blanket `> 0` decrement is correct only because the head
--    always leaves; with suspended holds being skipped it corrupts positions,
--    and a named regression test must fail under the old form."
--
--    The blanket form lives in three places in 1.0 — `reservations.service.ts`'s
--    promoter, `reservation-expiry.job.ts` and `loans.service.ts`'s return path
--    — and it is CORRECT there, because 1.0 has no suspension, so the hold that
--    leaves is always position 1 and decrementing everybody is decrementing
--    everybody behind it. The cancel path already uses the targeted form.
--
--    The moment a SUSPENDED hold can be skipped, the hold that leaves is not
--    the head. Concretely, five holds with #1 suspended, and #2 filled:
--
--      targeted   WHERE queue_position > 2   ->  1(susp), 2, 3, 4   correct
--      blanket    WHERE queue_position > 0   ->  0(susp), 2, 3, 4   position 0
--
--    `holds_position_is_one_based` makes the second line ABORT with `23514`
--    rather than commit a queue with no position 1 in it. That is what the named
--    regression test asserts, and a SQLSTATE is unambiguous and
--    order-independent where a multiset of positions is not: a subtly different
--    wrong implementation can still produce the right multiset.
--
-- 2. NO STATUS ENUM, AND THE ENDINGS ARE NULL TESTS.
--
--    A hold is open when `fulfilled_at`, `cancelled_at` and `expired_at` are all
--    NULL. Phase 15 measured the alternative on 200,053 rows and the numbers are
--    in `45-items.prisma`: a parameterised enum predicate seq-scans at 1470
--    buffers against 2 for a NULL predicate, still seq-scans with
--    `enable_seqscan = off` (so there is no index path at all), and
--    `ON CONFLICT … WHERE state = CAST($1::text AS …)` raises `42P10` while the
--    literal form works by hand in psql.
--
--    `holds_one_ending` is what makes the partial uniques mean what they say: a
--    row carrying two endings is excluded from an index by either of them, and a
--    second assignment would slip past `holds_one_assignment_per_item`. The same
--    argument `item_transfers_one_ending` already makes.
--
-- 3. A QUEUE POSITION EXISTS EXACTLY WHILE A HOLD IS WAITING.
--
--    Assigned is not queued: a hold that has been given a copy is still open and
--    is no longer in line. So `queue_position IS NOT NULL` iff the hold is open
--    AND unassigned — `holds_position_iff_waiting` — which is what lets the
--    partial unique on `(bib_id, queue_position)` be a plain NULL test and what
--    keeps a filled hold from occupying a slot nobody can have.
--
-- `prisma migrate deploy` does NOT wrap a migration file in a transaction, so
-- this file opens its own.

