-- ---------------------------------------------------------------------------
-- The two partial uniques §3 names, and the CHECKs that make them mean it
-- ---------------------------------------------------------------------------

-- §3's own phrase: "`holds_one_assignment_per_item` making a double-assigned
-- item impossible". A pure NULL predicate — see decision 2 in the header for why
-- it is not `WHERE status = 'assigned'`.
--
-- `assigned_item_id` is nullable and a partial unique treats NULLs as distinct
-- anyway, so the extra `IS NOT NULL` is not redundant: it keeps the index to the
-- handful of rows that actually hold a copy, instead of one entry per waiting
-- reader.
CREATE UNIQUE INDEX holds_one_assignment_per_item
  ON holds (assigned_item_id)
  WHERE assigned_item_id IS NOT NULL
    AND fulfilled_at IS NULL AND cancelled_at IS NULL AND expired_at IS NULL;

-- Two readers cannot share a slot. Contiguity and 1-basedness are AGGREGATE
-- properties no constraint reaches, so they live in the named regression test
-- and in `holds_position_is_one_based` below; uniqueness is the half a database
-- can prove, and it is the half that stops a rebalance colliding with a
-- placement.
--
-- NOTE FOR A LATER PHASE: `ON CONFLICT` can never arbitrate on this index to
-- pick the next free slot. Postgres requires an arbiter to match the index's
-- columns AND its predicate, and an upsert that wanted "the next position" would
-- have to know the position before it could name it. Positions are allocated by
-- `max(queue_position) + 1` under the `bib:` advisory lock, which is what makes
-- that read-then-write safe.
CREATE UNIQUE INDEX holds_one_hold_per_position
  ON holds (bib_id, queue_position)
  WHERE queue_position IS NOT NULL;

-- One reader, one live hold per record. A second is a mistake at a desk, not a
-- second place in the queue — and without this a double-click puts a reader in
-- line twice and hands them two copies.
CREATE UNIQUE INDEX holds_one_live_per_patron_bib
  ON holds (patron_id, bib_id)
  WHERE fulfilled_at IS NULL AND cancelled_at IS NULL AND expired_at IS NULL;

ALTER TABLE holds
  -- Decision 2. Exactly one ending, or none.
  ADD CONSTRAINT holds_one_ending
    CHECK (pg_catalog.num_nonnulls(fulfilled_at, cancelled_at, expired_at) <= 1),
  -- Decision 3. A position exists exactly while the hold is waiting.
  ADD CONSTRAINT holds_position_iff_waiting
    CHECK ((queue_position IS NOT NULL)
           = (assigned_item_id IS NULL
              AND fulfilled_at IS NULL AND cancelled_at IS NULL AND expired_at IS NULL)),
  -- DECISION 1, and the phase's acceptance criterion made enforceable. The 1.0
  -- blanket decrement aborts here with 23514 the first time a suspended hold at
  -- position 1 is skipped.
  ADD CONSTRAINT holds_position_is_one_based
    CHECK (queue_position IS NULL OR queue_position >= 1),
  -- A suspension is a window, not a moment.
  ADD CONSTRAINT holds_suspension_window
    CHECK (suspended_from IS NULL OR suspended_until IS NULL OR suspended_from <= suspended_until),
  -- An item-level hold names an item; a title-level one must not. The `volume`
  -- text is the same shape for a volume hold. Without this a request can claim a
  -- level it does not carry the data for, and the promotion filter then silently
  -- treats it as a title hold — which hands a reader the wrong physical thing.
  ADD CONSTRAINT holds_level_carries_its_target
    CHECK ((level <> 'item' OR item_id IS NOT NULL)
           AND (level <> 'volume' OR volume IS NOT NULL)
           AND (level <> 'title' OR (item_id IS NULL AND volume IS NULL))),
  -- The two halves of a fulfilment, and of an expiry. Half a record is a row
  -- somebody half-wrote.
  ADD CONSTRAINT holds_fulfilment_pair
    CHECK ((fulfilled_at IS NULL) = (fulfilled_by_loan_id IS NULL)),
  ADD CONSTRAINT holds_expiry_pair
    CHECK ((expired_at IS NULL) = (expired_kind IS NULL)),
  ADD CONSTRAINT holds_expired_kind_known
    CHECK (expired_kind IS NULL OR expired_kind IN ('shelf', 'request')),
  -- Collectable implies assigned. A hold cannot be on a shelf without a copy on
  -- it, and this is the state the routed-hold criterion turns on: for the whole
  -- of a transit the copy is assigned and `awaiting_pickup_since` is NULL.
  ADD CONSTRAINT holds_collectable_implies_assigned
    CHECK (awaiting_pickup_since IS NULL OR assigned_item_id IS NOT NULL),
  ADD CONSTRAINT holds_shelf_expiry_implies_collectable
    CHECK (shelf_expires_at IS NULL OR awaiting_pickup_since IS NOT NULL);

ALTER TABLE hold_groups
  ADD CONSTRAINT hold_groups_resolution_pair
    CHECK ((resolved_at IS NULL) = (resolved_by_hold_id IS NULL));

-- The hold shelf, and the pull list: two reads a desk does every morning.
--
-- Both are partial on a NULL test rather than on a status, for decision 2's
-- reason. The pull list is "assigned, not yet collectable" — the copies a
-- librarian has to physically fetch; the shelf is "collectable", ordered by the
-- date the reader will be told.
CREATE INDEX holds_pull_list_idx
  ON holds (pickup_branch_id, assigned_at)
  WHERE assigned_item_id IS NOT NULL AND awaiting_pickup_since IS NULL
    AND fulfilled_at IS NULL AND cancelled_at IS NULL AND expired_at IS NULL;

CREATE INDEX holds_shelf_idx
  ON holds (pickup_branch_id, shelf_expires_at)
  WHERE awaiting_pickup_since IS NOT NULL
    AND fulfilled_at IS NULL AND cancelled_at IS NULL AND expired_at IS NULL;

-- The request-expiry sweep, and the suspension resume. Both scan a small live
-- set out of a table that grows for ever.
CREATE INDEX holds_request_expiry_idx
  ON holds (request_expires_at)
  WHERE request_expires_at IS NOT NULL
    AND fulfilled_at IS NULL AND cancelled_at IS NULL AND expired_at IS NULL;

-- "How many copies does this record have?", which nothing could answer without a
-- scan.
--
-- `items_shelf_available_idx` is PARTIAL on `is_shelf_available`, so it serves
-- "how many are ON THE SHELF" and is useless for the denominator.
-- `countCirculationState` asks for both on every checkout and every hold
-- placement, because `allCopiesAvailable` is the ratio — and measured on a fresh
-- schema the denominator was a Seq Scan on `items`, which on a real catalogue is
-- the whole table on the hottest path in the building.
--
-- PARTIAL, and the predicate is doing two jobs. It matches the subquery's own
-- literal `archived_at IS NULL`, so the planner can prove it; and it makes the
-- index USELESS to the phase-15 hold-promotion probe, which carries no such
-- clause. That second job is the reason for the allowlist entry rather than a
-- plain `@@index([bibId])`: a plain index competes with
-- `items_shelf_available_idx` on an empty table, the planner picks either at
-- equal cost, and phase 15's `items.spec.ts` assertion that the probe uses the
-- two-column partial index starts flapping — an assertion about a real plan,
-- broken by an index that is worse for that query.
--
-- Prisma has no partial-index concept and does not SEE one either: `migrate
-- diff` emits no DROP for a partial btree index, which is why
-- `circulation_rules_default_singleton` and the three partial uniques below need
-- no allowlist entry in `check-schema-drift.ts` and this one does not either.
-- (Verified by adding an entry and watching the gate refuse it as an exception
-- that no longer describes the tree.)
CREATE INDEX items_bib_idx ON items (bib_id) WHERE archived_at IS NULL;

